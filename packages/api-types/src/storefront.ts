import type { ProductStatus } from './enums';

/**
 * Shopper-facing read models.
 *
 * These are projections assembled across several tables by
 * `@installment/commerce`'s `StorefrontService`, not table rows — which is why
 * they live apart from `domain.ts`. `Product` there is what a merchant writes;
 * `StorefrontProduct` here is what a shopper sees, and the two have drifted
 * apart deliberately: a shopper needs a vendor name, an image URL and a rating,
 * and none of those are columns on `products`.
 *
 * Every amount is integer pesewas (GHS × 100). Every timestamp is ISO-8601.
 */

/** A product as a shopping surface renders a card. */
export interface StorefrontProduct {
  id: string;
  store_id: string;
  merchant_id: string;
  category_id: string | null;
  title: string;
  base_price_pesewas: number;
  /** The "was" price, when there is one. Advisory only — never charged. */
  compare_at_price_pesewas: number | null;
  /** Whole percent off, or null when there is nothing to compare against. */
  discount_percent: number | null;
  deal_ends_at: string | null;
  currency: string;
  /** Resolved against MEDIA_BASE_URL; null when storage is not configured. */
  primary_image_url: string | null;
  primary_image_alt: string | null;
  store_slug: string;
  store_display_name: string;
  store_logo_url: string | null;
  store_verified: boolean;
  rating_avg: number | null;
  rating_count: number;
  sold_count: number;
  /** Whether any active instalment offer covers this product. */
  installment_eligible: boolean;
  in_stock: boolean;
  created_at: string;
}

export interface StorefrontStore {
  id: string;
  slug: string;
  display_name: string;
  about: string | null;
  city: string | null;
  region: string | null;
  verified: boolean;
  logo_url: string | null;
  banner_url: string | null;
  support_phone: string | null;
  joined_at: string;
  product_count: number;
  rating_avg: number | null;
  rating_count: number;
  order_count: number;
  /** Share of delivered orders that arrived by their ETA, 0–100; null when none. */
  on_time_percent: number | null;
}

export interface StorefrontCategory {
  id: string;
  parent_id: string | null;
  name: string;
  slug: string;
  position: number;
  image_url: string | null;
  accent_hex: string | null;
  product_count: number;
}

export interface StorefrontVariant {
  id: string;
  sku: string;
  option_values: Record<string, unknown>;
  price_pesewas: number | null;
  /** What is actually charged: the variant's override, else the product's base. */
  effective_price_pesewas: number;
  is_active: boolean;
  /** Sellable units — available minus reserved. */
  quantity_available: number;
}

export interface StorefrontImage {
  id: string;
  url: string | null;
  alt_text: string | null;
  position: number;
}

export interface StorefrontProductDetails extends StorefrontProduct {
  description: string | null;
  attributes: Record<string, unknown>;
  images: StorefrontImage[];
  /** Inactive variants are filtered out — they cannot be bought. */
  variants: StorefrontVariant[];
  /** The single option axis the picker labels itself with, e.g. "SIZE". */
  variant_label: string | null;
  plan_template_ids: string[];
  store: StorefrontStore;
  category: { id: string; name: string; slug: string } | null;
}

export interface StorefrontReview {
  id: string;
  rating: number;
  title: string | null;
  body: string | null;
  /** First name plus a surname initial — reviews are public. */
  author: string;
  created_at: string;
}

export interface HomeFeed {
  categories: StorefrontCategory[];
  deals: StorefrontProduct[];
  /** When the soonest live deal ends — what a countdown must track. */
  deals_end_at: string | null;
  installment_picks: StorefrontProduct[];
  newest: StorefrontProduct[];
}

export interface TrendingTerm {
  term: string;
  searches: number;
}

export interface PickupHub {
  id: string;
  name: string;
  region: string;
  city: string;
  area: string | null;
  detail: string | null;
  is_active: boolean;
  position: number;
}

export interface DeliveryQuote {
  fulfilment_method: 'courier';
  fee_pesewas: number;
  eta_min_days: number;
  eta_max_days: number;
  eta_earliest: string;
  eta_latest: string;
  /** Which zone answered: a city rule, a region rule, or the national fallback. */
  matched: 'city' | 'region' | 'national';
}

/** One row of a quoted schedule. */
export interface QuotedInstallment {
  sequence_number: number;
  kind: 'down_payment' | 'installment';
  amount_pesewas: number;
  due_date: string;
  grace_until_date: string;
}

/**
 * What an instalment plan would cost, generated by the engine's own
 * `ScheduleGenerator` — so a quote is the contract, not an approximation.
 *
 * Note `number_of_installments` EXCLUDES the deposit; `installments.length`
 * includes it. Anything counting payments for display should use the array.
 */
export interface PlanQuote {
  plan_template_id: string;
  name: string;
  description: string | null;
  business_model: string;
  number_of_installments: number;
  installment_frequency_days: number;
  grace_period_days: number;
  down_payment_bps: number;
  interest_rate_bps: number;
  service_fee_flat_pesewas: number;
  late_fee_bps_per_week: number;
  late_fee_cap_bps: number;
  min_amount_pesewas: number;
  max_amount_pesewas: number;
  down_payment_pesewas: number;
  financed_amount_pesewas: number;
  total_interest_pesewas: number;
  total_fees_pesewas: number;
  total_payable_pesewas: number;
  per_installment_pesewas: number;
  installments: QuotedInstallment[];
  eligible: boolean;
  ineligible_reason: string | null;
}

/** Kept so a consumer can narrow on the same union the catalogue uses. */
export type StorefrontProductStatus = ProductStatus;
